import fs from "node:fs/promises";
import path from "node:path";
import { build } from "esbuild";

const result = await build({
  entryPoints: ["apps/web/mcp-review-view/main.ts"],
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "es2022",
  minify: true,
  write: false,
  logLevel: "silent",
});
const javascript = result.outputFiles?.[0]?.text;
if (!javascript) throw new Error("Missing MCP Review Apps client bundle");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>BoardReadyOps Review</title><style>
:root{color-scheme:light dark;font:14px system-ui,sans-serif}body{margin:0;padding:16px;max-width:640px}h1{font-size:16px;margin:0 0 12px}.status{opacity:.75;font-size:12px}.card{border:1px solid #7e899777;border-radius:12px;padding:14px}.counts{font-size:19px;font-weight:600;margin:12px 0}button{font:inherit;border:1px solid currentColor;border-radius:7px;padding:6px 10px;background:transparent;cursor:pointer}pre{white-space:pre-wrap;overflow-wrap:anywhere;font-size:11px}footer{font-size:11px;opacity:.7;margin-top:12px}
</style></head><body><main class="card"><h1 id="heading">BoardReadyOps · PCB Review</h1><p class="status" id="status">Waiting for authorized source evidence…</p><p class="counts" id="counts"></p><button type="button" id="detail-button" hidden>Show provenance</button><pre id="provenance" hidden></pre><footer>Evidence only, not a fabrication approval or electrical safety certification.</footer></main><script>${javascript.replace(/<\/script/gi, "<\\/script")}</script></body></html>`;
if (Buffer.byteLength(html) > 1_500_000) throw new Error("MCP Apps Review HTML exceeds 1.5 MB");
const target = path.resolve("apps/web/lib/generated-mcp-review-view.ts");
const output = `// biome-ignore-all format lint/suspicious/noTemplateCurlyInString: generated bundle.\n// Generated by scripts/build-mcp-review-view.mjs. Do not edit by hand.\nexport const mcpReviewViewHtml = ${JSON.stringify(html)};\n`;
if (process.argv.includes("--check")) {
  if ((await fs.readFile(target, "utf8")) !== output) throw new Error("Generated MCP Apps view is stale");
} else {
  await fs.writeFile(target, output);
}
